#!/usr/bin/env bash
# Generates build/ts_registry.inc: a table of all tree-sitter grammars and queries,
# so that everything is compiled into the binary.
# Usage: tools/gen-registry.sh third_party > build/ts_registry.inc
set -euo pipefail
TP="$1"

echo '// Generated by tools/gen-registry.sh - do not edit by hand.'
echo
echo 'extern "C" {'
entries=()
while IFS= read -r p; do
  name="${p#"$TP/grammars/"}"; name="${name%%/*}"
  fn="$(grep -o 'TSLanguage \*tree_sitter_[a-z0-9_]*(void)' "$p" | head -1 | sed 's/.*\*//; s/(void)//')"
  [ -n "$fn" ] || { echo "no entry point found in $p" >&2; exit 1; }
  echo "const TSLanguage *$fn(void);"
  entries+=("    {\"$name\", $fn},")
done < <(find "$TP/grammars" -name parser.c | sort)
echo '}'
echo
echo 'struct TsGrammarEntry { const char* name; const TSLanguage* (*fn)(void); };'
echo 'static const TsGrammarEntry TS_GRAMMARS[] = {'
printf '%s\n' "${entries[@]}"
echo '};'
echo
echo 'struct TsQueryEntry { const char* lang; const char* kind; const char* text; };'
echo 'static const TsQueryEntry TS_QUERIES[] = {'
for d in $(find "$TP/queries" -mindepth 1 -maxdepth 1 -type d | sort); do
  lang="$(basename "$d")"
  for kind in highlights injections indents; do
    f="$d/$kind.scm"
    [ -f "$f" ] || continue
    printf '    {"%s", "%s", R"__TSQ__(' "$lang" "$kind"
    cat "$f"
    printf ')__TSQ__"},\n'
  done
done
echo '};'
